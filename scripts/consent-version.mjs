// Single source of truth for the cookie-consent schema version is the
// `var VERSION = N;` line in public/consent/gw-consent.js (the static script
// shared with app.gatherwise.io). This reads it and writes
// lib/consent-version.generated.ts so the /api/consent route uses the same
// number. Runs automatically before dev, build and tests (see package.json).
// To re-ask everyone, edit VERSION in gw-consent.js — nothing else.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SCRIPT_PATH = join(root, "public/consent/gw-consent.js");
const OUT_PATH = join(root, "lib/consent-version.generated.ts");

export function readScriptVersion() {
  const src = readFileSync(SCRIPT_PATH, "utf8");
  const matches = [...src.matchAll(/^\s*var VERSION = (\d+);/gm)];
  if (matches.length !== 1) {
    throw new Error(
      `Expected exactly one "var VERSION = <number>;" line in ${SCRIPT_PATH}, found ${matches.length}`,
    );
  }
  return Number(matches[0][1]);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const version = readScriptVersion();
  const out =
    "// GENERATED by scripts/consent-version.mjs from public/consent/gw-consent.js.\n" +
    "// Do not edit; change VERSION in gw-consent.js instead.\n" +
    `export const CONSENT_VERSION = ${version};\n`;
  let prev = null;
  try { prev = readFileSync(OUT_PATH, "utf8"); } catch {}
  if (prev !== out) writeFileSync(OUT_PATH, out);
  console.log(`consent version: ${version}`);
}
